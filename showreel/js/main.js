/* =============================================================================
 * main.js — transport + compositing.
 * GSAP drives the master clock; HyperFrames renders every frame as a pure
 * function of time. Transitions are hard-edged composites only:
 *   · Paper → Blueprint : hard-edged shape flood
 *   · Blueprint → Holo  : single horizontal scan line
 *   · Hologram → Paper  : single horizontal scan line
 * No cuts. No dissolves. First frame ≡ final frame.
 * ========================================================================== */

(() => {
  'use strict';
  const { W, H } = HF.STAGE;
  const C = HF.COLOR;

  const canvas = document.getElementById('stage');
  const ctx = canvas.getContext('2d');
  canvas.width = W;
  canvas.height = H;

  /* ---- deterministic render (shared compositor) ---------------------------- */

  function render(tRaw) {
    RENDER.frame(ctx, tRaw);
  }

  /* ---- GSAP master transport ---------------------------------------------- */

  const playhead = { t: 0 };
  let playing = true;

  const tl = gsap.timeline({
    repeat: -1,
    paused: true,
    onUpdate: () => {
      render(playhead.t);
      syncUI();
    }
  });
  tl.to(playhead, { t: HF.DURATION, duration: HF.DURATION, ease: 'none' });

  /* ---- optional score ------------------------------------------------------
   * audio/score.wav is generated by audio/score.py (120 BPM, beat-locked).
   * If present it plays in sync; the reel is silent-safe without it.
   * ------------------------------------------------------------------------ */
  const audioEl = document.getElementById('score');
  let audioOK = false;
  if (audioEl) {
    audioEl.addEventListener('canplaythrough', () => { audioOK = true; }, { once: true });
    audioEl.addEventListener('error', () => { audioOK = false; }, { once: true });
    audioEl.load();
  }

  function audioSeek(t) {
    if (!audioOK) return;
    try {
      if (Math.abs(audioEl.currentTime - t) > 0.12) audioEl.currentTime = t % 60;
    } catch (_) { /* not ready */ }
  }

  /* ---- UI ------------------------------------------------------------------ */

  const scrub = document.getElementById('scrub');
  const timeEl = document.getElementById('timecode');
  const stageEl = document.getElementById('stage-name');
  const figEl = document.getElementById('fig-name');
  const playBtn = document.getElementById('playpause');

  function syncUI() {
    const t = playhead.t;
    scrub.value = String(t);
    const frame = Math.floor(t * HF.FPS) % HF.FRAMES;
    timeEl.textContent = `00:${HF.pad(Math.floor(t / 60) % 60, 2)}:${HF.pad(Math.floor(t) % 60, 2)} · F ${HF.pad(frame, 4)}`;
    stageEl.textContent = SCENES.skinAt(t).toUpperCase();
    figEl.textContent = `FIG. ${HF.pad(HF.barIndex(t) + 1, 2)} — ${HF.BAR_NAMES[HF.barIndex(t)]}`;
  }

  playBtn.addEventListener('click', () => {
    playing = !playing;
    if (playing) {
      tl.play();
      if (audioOK) { audioSeek(playhead.t); audioEl.play().catch(() => {}); }
      playBtn.textContent = 'PAUSE';
    } else {
      tl.pause();
      if (audioOK) audioEl.pause();
      playBtn.textContent = 'PLAY';
    }
  });

  scrub.addEventListener('input', () => {
    const t = parseFloat(scrub.value);
    tl.seek(t, false);
    playhead.t = t;
    render(t);
    syncUI();
    audioSeek(t);
  });

  window.addEventListener('keydown', (e) => {
    if (e.code === 'Space') { e.preventDefault(); playBtn.click(); }
    if (e.code === 'ArrowRight') { tl.seek(Math.min(60, playhead.t + 1 / 60), false); playhead.t = tl.time() % 60; render(playhead.t); syncUI(); }
    if (e.code === 'ArrowLeft') { tl.seek(Math.max(0, playhead.t - 1 / 60), false); playhead.t = tl.time() % 60; render(playhead.t); syncUI(); }
    if (e.code === 'KeyR') { tl.seek(0, false); playhead.t = 0; render(0); syncUI(); }
  });

  /* ---- boot ---------------------------------------------------------------- */

  const params = new URLSearchParams(location.search);

  function boot() {
    SCENES.measureHead(ctx);

    const frameParam = params.get('frame');
    const tParam = params.get('t');

    if (frameParam !== null) {
      // deterministic single-frame render (export mode)
      playing = false;
      playBtn.textContent = 'PLAY';
      playhead.t = (parseInt(frameParam, 10) / HF.FPS) % HF.DURATION;
      render(playhead.t);
      syncUI();
      return;
    }
    if (tParam !== null) {
      playhead.t = parseFloat(tParam) % HF.DURATION;
      render(playhead.t);
      syncUI();
    } else {
      render(0);
      syncUI();
    }
    if (params.get('paused') === '1') {
      playing = false;
      playBtn.textContent = 'PLAY';
    } else {
      tl.play();
      if (audioOK) { audioSeek(0); audioEl.play().catch(() => {}); }
      playing = true;
      playBtn.textContent = 'PAUSE';
    }
    requestAnimationFrame(loop);
  }

  let last = performance.now();
  function loop() {
    requestAnimationFrame(loop);
    // keep UI timecode honest even when GSAP advances
    if (playing) syncUI();
    last = performance.now();
  }

  // Load Geist (variable 100–900) then start.
  const face = new FontFace('Geist', 'url(vendor/Geist-Variable.woff2)', {
    weight: '100 900', style: 'normal'
  });
  face.load().then((f) => {
    document.fonts.add(f);
    return document.fonts.ready;
  }).then(boot).catch((err) => {
    console.error('font load failed', err);
    boot(); // fall back to sans-serif metrics
  });
})();
