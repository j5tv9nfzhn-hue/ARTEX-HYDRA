const SIDEBAR_COOKIE_NAME = "sidebar_state"
const SIDEBAR_COOKIE_MAX_AGE = 60 * 60 * 24 * 7
const SIDEBAR_WIDTH = "16rem"
const SIDEBAR_WIDTH_MOBILE = "18rem"
const SIDEBAR_WIDTH_ICON = "3rem"
const SIDEBAR_KEYBOARD_SHORTCUT = "b"

// Hover-Reveal as Fixed Overlay 的时序（开启 180ms / 关闭 260ms）与状态机
// 都在 @/lib/sidebar-reveal，那里有单测；本文件只负责把 DOM 事件接过去。
// 覆盖层展开是「临时视觉状态」，不进 SidebarProvider 的 open/close 语义。
// 单独开一个小 context 给子组件（如 SidebarMenuButton 的 tooltip）用：
// 展开时标签已经可见，再弹 tooltip 就是两层重复文字。
const SidebarRevealContext = React.createContext(false)

function useSidebarRevealed() {
  return React.useContext(SidebarRevealContext)
}

/**
 * 覆盖层展开态的只读查询。给需要「按展开/收起切换渲染分支」的导航组件用：
 * 那些分支在 JS 里读 `state === "collapsed"`，而覆盖层展开时 state 仍是
 * collapsed，只看 state 会把「看起来已展开」的侧栏当成图标轨道渲染。
 */
export function useSidebarIsRevealed() {
  return useSidebarRevealed()
}

type SidebarContextProps = {
  state: "expanded" | "collapsed"
  open: boolean
  setOpen: (open: boolean) => void
  openMobile: boolean
  setOpenMobile: (open: boolean) => void
  isMobile: boolean
  toggleSidebar: () => void
}

const SidebarContext = React.createContext<SidebarContextProps | null>(null)

function useSidebar() {
  const context = React.useContext(SidebarContext)
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.")
  }

  return context
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean
  open?: boolean
  onOpenChange?: (open: boolean) => void
}) {
  const isMobile = useIsMobile()
  const [openMobile, setOpenMobile] = React.useState(false)

  // This is the internal state of the sidebar.
  // We use openProp and setOpenProp for control from outside the component.
  const [_open, _setOpen] = React.useState(defaultOpen)
  const open = openProp ?? _open
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value
      if (setOpenProp) {
        setOpenProp(openState)
      } else {
        _setOpen(openState)
      }

      // This sets the cookie to keep the sidebar state.
      document.cookie = `${SIDEBAR_COOKIE_NAME}=${openState}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`
    },
    [setOpenProp, open]
  )

  // Helper to toggle the sidebar.
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open)
  }, [isMobile, setOpen, setOpenMobile])

  // Adds a keyboard shortcut to toggle the sidebar.
  React.useEffect(() => {
    const handleKeyDown = (event: KeyboardEvent) => {
      if (
        event.key === SIDEBAR_KEYBOARD_SHORTCUT &&
        (event.metaKey || event.ctrlKey)
      ) {
        event.preventDefault()
        toggleSidebar()
      }
    }

    window.addEventListener("keydown", handleKeyDown)
    return () => window.removeEventListener("keydown", handleKeyDown)
  }, [toggleSidebar])

  // We add a state so that we can do data-state="expanded" or "collapsed".
  // This makes it easier to style the sidebar with Tailwind classes.
  const state = open ? "expanded" : "collapsed"

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar]
  )

  return (
    <SidebarContext.Provider value={contextValue}>
      <div
        data-slot="sidebar-wrapper"
        style={
          {
            "--sidebar-width": SIDEBAR_WIDTH,
            "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
            ...style,
          } as React.CSSProperties
        }
        className={cn(
          "group/sidebar-wrapper flex min-h-svh w-full has-data-[variant=inset]:bg-sidebar",
          className
        )}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  )
}

function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  className,
  children,
  dir,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right"
  variant?: "sidebar" | "floating" | "inset"
  collapsible?: "offcanvas" | "icon" | "none"
}) {
  const { isMobile, state, openMobile, setOpenMobile } = useSidebar()

  // ---- Hover-Reveal as Fixed Overlay ----
  //
  // 只在「桌面端 + 图标折叠模式 + 当前已折叠」三种条件同时成立时才生效：
  //   - 展开（pinned）时本来就有内容宽度，不需要覆盖层；
  //   - offcanvas 折叠时整条被移出视口，没有可悬停的轨道；
  //   - 移动端走 Sheet，悬停无意义。
  //
  // 关键点：侧栏容器本来就是 position: fixed，天然浮在内容之上。
  // 真正挤占宽度的只有 sidebar-gap 这个占位元素，所以覆盖层展开
  // 只需要「放大 fixed 容器 + 把子组件切回展开态」，占位宽度一动不动——
  // 内容区不会重排，这正是把右侧面板从窄缝里救出来的原因。
  //
  // 计时与状态翻转全部交给 src/lib/sidebar-reveal.ts（可单测），
  // 这里只把 DOM 事件翻译成它的四个动作。
  const canReveal = !isMobile && collapsible === "icon" && state === "collapsed"
  const [revealed, setRevealed] = React.useState(false)
  const reveal = React.useMemo(() => createRevealController(setRevealed), [])

  React.useEffect(() => {
    reveal.setEnabled(canReveal)
  }, [reveal, canReveal])

  React.useEffect(() => () => reveal.dispose(), [reveal])

  // Esc 收起覆盖层：展开态盖住了内容，必须留一个不依赖指针的退出方式。
  React.useEffect(() => {
    if (!revealed) return
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") reveal.escape()
    }
    window.addEventListener("keydown", onKeyDown)
    return () => window.removeEventListener("keydown", onKeyDown)
  }, [revealed, reveal])

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
          className
        )}
        {...props}
      >
        {children}
      </div>
    )
  }

  if (isMobile) {
    return (
      <Sheet open={openMobile} onOpenChange={setOpenMobile} {...props}>
        <SheetContent
          dir={dir}
          data-sidebar="sidebar"
          data-slot="sidebar"
          data-mobile="true"
          className="w-(--sidebar-width) bg-sidebar p-0 text-sidebar-foreground [&>button]:hidden"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH_MOBILE,
            } as React.CSSProperties
          }
          side={side}
        >
          <SheetHeader className="sr-only">
            <SheetTitle>侧边栏</SheetTitle>
            <SheetDescription>显示移动端侧边栏。</SheetDescription>
          </SheetHeader>
          <div className="flex h-full w-full flex-col">{children}</div>
        </SheetContent>
      </Sheet>
    )
  }

  // 图标折叠且未展开覆盖层时，占位与容器都应是窄轨道。
  // 这里刻意用 JS 布尔量而不是 group-data 选择器：覆盖层展开会把
  // data-collapsible 临时清空（让子组件切回展开态），若占位宽度也挂在
  // group-data 上，它就会跟着变宽——那正是我们要避免的内容重排。
  const iconCollapsed = state === "collapsed" && collapsible === "icon"

  return (
    <SidebarRevealContext.Provider value={revealed}>
      <div
        className="group peer hidden text-sidebar-foreground md:block"
        data-state={state}
        data-collapsible={state === "collapsed" && !revealed ? collapsible : ""}
        data-reveal={canReveal && revealed ? "true" : undefined}
        data-variant={variant}
        data-side={side}
        data-slot="sidebar"
        onPointerEnter={(event) => {
          // 触屏也会派发 pointerenter：不挡掉的话，点一下图标就会因为
          // 悬停意图被误判成"想看侧边栏"。触摸设备走原生的点击展开。
          if (event.pointerType === "touch") return
          reveal.pointerEnter()
        }}
        onPointerLeave={() => reveal.pointerLeave()}
        onFocusCapture={() => reveal.focusIn()}
        onBlurCapture={(event) => {
          // 焦点在侧栏内部移动不算离开；只有真正移出去才收起。
          const next = event.relatedTarget
          reveal.focusOut(next instanceof Node && event.currentTarget.contains(next))
        }}
      >
        {/* This is what handles the sidebar gap on desktop */}
        <div
          data-slot="sidebar-gap"
          className={cn(
            "relative w-(--sidebar-width) bg-transparent transition-[width] duration-200 ease-linear motion-reduce:transition-none",
            "group-data-[collapsible=offcanvas]:w-0",
            "group-data-[side=right]:rotate-180",
            iconCollapsed &&
              (variant === "floating" || variant === "inset"
                ? "w-[calc(var(--sidebar-width-icon)+(--spacing(4)))]"
                : "w-(--sidebar-width-icon)")
          )}
        />
        <div
          data-slot="sidebar-container"
          data-side={side}
          className={cn(
            "fixed inset-y-0 z-10 hidden h-svh w-(--sidebar-width) transition-[left,right,width] duration-200 ease-linear data-[side=left]:left-0 data-[side=left]:group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)] data-[side=right]:right-0 data-[side=right]:group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)] motion-reduce:transition-none md:flex",
            // 宽度动画期间每帧都会重排这一列。contain:layout 把重排/重绘范围
            // 圈在本元素内，不让它波及整页（侧栏是 fixed，本来也不该影响外部）。
            "[contain:layout]",
            // Adjust the padding for floating and inset variants.
            variant === "floating" || variant === "inset"
              ? "p-2 group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4))+2px)]"
              : "group-data-[collapsible=icon]:w-(--sidebar-width-icon) group-data-[side=left]:border-r group-data-[side=right]:border-l",
            // 覆盖层形态：抬高层级并加投影，明确"这是一层浮在内容上的东西"，
            // 而不是把正文挤走的新布局。投影只用 lg：宽展动画期间它会跟着
            // 每帧重绘，xl 的大模糊半径是最容易被看出来的掉帧来源。
            revealed && canReveal && "z-30 shadow-lg",
            className
          )}
          {...props}
        >
          <div
            data-sidebar="sidebar"
            data-slot="sidebar-inner"
            className="flex size-full flex-col bg-sidebar group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:shadow-sm group-data-[variant=floating]:ring-1 group-data-[variant=floating]:ring-sidebar-border"
          >
            {children}
          </div>
        </div>
      </div>
    </SidebarRevealContext.Provider>
  )
}

