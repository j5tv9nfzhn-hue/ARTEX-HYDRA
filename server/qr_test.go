func TestQRMatrixRowsMatchGolden(t *testing.T) {
	for payload, want := range qrGoldenCases() {
		got, err := QRMatrixRows(payload)
		if err != nil {
			t.Fatalf("编码 %q 失败：%v", payload, err)
		}
		if len(got) != len(want) {
			t.Fatalf("编码 %q 的行数 ＝ %d，期望 %d", payload, len(got), len(want))
		}
		for i := range want {
			if got[i] != want[i] {
				t.Fatalf("编码 %q 第 %d 行不一致\n实际：%s\n期望：%s", payload, i, got[i], want[i])
			}
		}
	}
}

func TestQRCodeSVGRejectsLongInput(t *testing.T) {
	if _, err := QRCodeSVG(strings.Repeat("x", 400)); err == nil {
		t.Fatal("超长内容应当报错，而不是编出一个读不出来的码")
	}
}
